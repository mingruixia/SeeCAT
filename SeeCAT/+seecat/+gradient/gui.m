function F = gui()
% GUI  Form description of connectivity gradients.
f = @seecat.gui.field;
F = f('input_dir', 'Derivatives folder', 'folder', 'Input', 'help', sprintf([ ...
    'The SeeCAT derivatives folder written by the Preprocessing or fMRIPrep page, e.g. ' ...
    'D:/study/bids/derivatives/seecat. Every run found there is used (or those chosen under ' ...
    'Selection); they are analysed together because their gradients are aligned to each other.']));
F(end+1) = f('input', 'Input series', 'text', 'Input', 'help', sprintf([ ...
    'Which series of each run is used: denoised (default; unsmoothed) or another desc label ' ...
    'such as denoisedSm6. Voxel nodes average their voxels anyway, so smoothing adds little.']));
F(end+1) = f('space', 'Space', 'text', 'Input', 'advanced', true, 'help', ...
    'Needed only when the derivatives hold the runs in more than one space. Empty: the only space present.');
F(end+1) = f('nodes', 'Nodes', 'choice', 'Nodes', 'choices', {'voxels', 'atlas'}, 'help', sprintf([ ...
    'What the connectivity matrix is built between.\n\n' ...
    'voxels (default): the cells of a grid of Node size in MNI space inside the Mask; each ' ...
    'node''s signal is the mean of the data voxels in it. Gives voxel-wise gradient maps.\n' ...
    'atlas: the parcels of an atlas image (e.g. Schaefer 400 in MNI space); fast, and the ' ...
    'values are also written as a table per run.\n\n' ...
    'Time and memory grow with the SQUARE of the number of nodes (see Node size).']));
F(end+1) = f('node_size', 'Node size (mm)', 'number', 'Nodes', 'help', sprintf([ ...
    'voxels only: the grid spacing. Nodes in the grey-matter mask, and the memory one run needs ' ...
    '(about three node x node matrices, a fourth with group alignment):\n' ...
    '  8 mm:  2 700 nodes, < 0.3 GB, about 1 s per run\n' ...
    '  6 mm:  6 500 nodes, about 1.3 GB, about 3 s per run\n' ...
    '  5 mm: 11 200 nodes, about 2 GB, about 10 s per run\n' ...
    '  4 mm: 22 000 nodes, about 7 GB, about 30 s per run (default)\n' ...
    '  3 mm: 52 000 nodes, about 40 GB and several minutes per run: workstations only.\n' ...
    '(Times measured on a 32-core desktop with 200-volume runs; fewer cores take longer.)\n' ...
    'With the brain mask there are about a third more nodes. Each parallel worker needs this ' ...
    'memory again. SeeCAT checks the free memory before it starts and stops with advice when ' ...
    'it is not enough.']));
F(end+1) = f('mask', 'Mask', 'mask', 'Nodes', 'help', sprintf([ ...
    'voxels only: where the nodes are.\n\n' ...
    'Grey matter (gm, default): cells at least half inside SeeCAT''s grey-matter mask; the usual ' ...
    'choice (Margulies et al. 2016 used cortex).\n' ...
    'Whole brain (brain): cells inside the brain mask, including white matter.\n' ...
    'Mask file: your own NIfTI mask in MNI space, e.g. cortex only.']));
F(end+1) = f('atlas', 'Atlas', 'file', 'Nodes', 'help', sprintf([ ...
    'atlas only: a NIfTI image in MNI space whose voxels hold integer parcel labels (0 = ' ...
    'background), e.g. Schaefer2018_400Parcels_7Networks_order_FSLMNI152_2mm.nii.gz. Every ' ...
    'label becomes a node; the gradient maps paint each parcel with its value.']));
F(end+1) = f('n_components', 'Components', 'number', 'Embedding', 'advanced', true, 'help', sprintf([ ...
    'How many gradients are computed and used in the alignment, 10 by default (BrainSpace). ' ...
    'More components make the alignment more stable; they cost little.']));
F(end+1) = f('n_maps', 'Maps written', 'number', 'Embedding', 'help', sprintf([ ...
    'How many gradients are written per run, 3 by default (desc-grad1, grad2, grad3 ...). ' ...
    'Gradient 1 explains the most variance (usually sensory to default-mode cortex), gradient 2 ' ...
    'the next (often visual to somatomotor), and so on. The eigenvalues of all components are ' ...
    'in the JSON sidecars and the group table.']));
F(end+1) = f('sparsity', 'Sparsity', 'number', 'Embedding', 'advanced', true, 'help', sprintf([ ...
    'Share of each node''s connections set to 0 before the affinity, keeping only its ' ...
    'strongest ones: 0.9 (default) keeps the top 10%%, as Margulies et al. 2016 and BrainSpace.']));
F(end+1) = f('kernel', 'Affinity', 'choice', 'Embedding', 'choices', {'normalized_angle', 'cosine', 'none'}, ...
    'advanced', true, 'help', sprintf([ ...
    'How similar two nodes'' connectivity profiles are.\n\n' ...
    'normalized_angle (default): 1 - angle/pi between the profiles; BrainSpace''s recommendation.\n' ...
    'cosine: cosine similarity, negative values set to 0 (Margulies et al. 2016).\n' ...
    'none: the sparsified connectivity itself (symmetrised).']));
F(end+1) = f('alpha', 'Diffusion alpha', 'number', 'Embedding', 'advanced', true, 'help', sprintf([ ...
    'Anisotropy of the diffusion map: 0.5 (default) lowers the influence of how densely ' ...
    'nodes are sampled (Coifman & Lafon 2006); 0 is a Laplacian eigenmap, 1 the ' ...
    'Laplace-Beltrami operator.']));
F(end+1) = f('align', 'Alignment', 'choice', 'Embedding', 'choices', {'group', 'procrustes', 'none'}, ...
    'help', sprintf([ ...
    'Gradients of separate runs can come out in a different order or sign; alignment makes ' ...
    'gradient k comparable across runs, which group statistics need.\n\n' ...
    'group and procrustes both use generalized Procrustes, as BrainSpace: every run is rotated ' ...
    '(rotation and sign flips only, no scaling) onto a reference, the mean of the rotated runs ' ...
    'becomes the new reference, and this repeats up to 10 times or until the reference changes ' ...
    'by less than 1e-5. They differ in the first reference:\n' ...
    'group (default): the gradients of the group-mean connectivity matrix, so gradient k keeps ' ...
    'its group-level meaning. Needs one more node x node matrix of memory. These starting ' ...
    'gradients are also written (desc-grad<k>_groupmatrix).\n' ...
    'procrustes: the first run''s gradients; no group matrix.\n' ...
    'none: each run''s own gradients; only for looking at single runs.']));
F = [F, seecat.gui.common(true)];
F(end+1) = seecat.gui.qc_field('Selection');
k = strcmp({F.path}, 'n_workers');
F(k).help = sprintf([ ...
    'Runs computed at the same time, each on a worker of a parallel pool. Every worker needs ' ...
    'the memory of one run (see Node size) plus about 1 GB, and with group alignment the main ' ...
    'MATLAB keeps about four node x node matrices for the group step.\n\n' ...
    '0: one after another (default).\n' ...
    'auto: as many workers as fit in 85%% of the free memory after that (at most one per core ' ...
    'and per run); e.g. with 4 mm nodes and 64 GB free, about 5 workers. The log shows the ' ...
    'estimate.\nA number: at most that many; SeeCAT stops before starting if they cannot fit.']);
end
