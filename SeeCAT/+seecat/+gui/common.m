function F = common(selection)
% COMMON  Form entries for the options every per-subject pipeline shares.
%   F = seecat.gui.common(true)    % with subject/session/task/run selection
F = seecat.gui.field('output_dir', 'Output folder', 'folder', 'Output', 'help', sprintf([ ...
    'Where the results go. Empty: the default of the pipeline, next to the input (for the ' ...
    'analyses, the derivatives folder itself, so the maps sit beside the runs they come from).\n\n' ...
    'Set it to keep the results of different settings apart, e.g. D:/study/derivatives/degree_r03. ' ...
    'Logs and the config of every run are written to its logs folder.']));
F(end+1) = seecat.gui.field('work_dir', 'Work folder', 'folder', 'Output', 'advanced', true, 'help', sprintf([ ...
    'Intermediate files, one subfolder per unit. Empty: seecat_work next to the output folder.\n\n' ...
    'It is deleted after a unit succeeds (unless Keep work files) and kept after a failure, so ' ...
    'a rerun does not redo finished steps. A fast local disk helps.']));
if selection
    F(end+1) = seecat.gui.field('subjects', 'Subjects', 'labels', 'Selection', 'help', sprintf([ ...
        'Which subjects to process: labels without "sub-", comma separated, e.g. 01, 02, 15. ' ...
        'Empty: all subjects found.']));
    F(end+1) = seecat.gui.field('sessions', 'Sessions', 'labels', 'Selection', 'advanced', true, 'help', ...
        'Labels without "ses-", comma separated, e.g. 1, 2. Empty: all sessions.');
    F(end+1) = seecat.gui.field('task', 'Task', 'text', 'Selection', 'help', sprintf([ ...
        'The task label of the runs, e.g. rest. Empty: the only task present; if the data hold ' ...
        'several tasks, name one.']));
    F(end+1) = seecat.gui.field('runs', 'Runs', 'labels', 'Selection', 'advanced', true, 'help', ...
        'Run labels, comma separated, e.g. 1, 2. Empty: all runs.');
end
F(end+1) = seecat.gui.field('n_workers', 'Parallel workers', 'number', 'Run', 'help', sprintf([ ...
    'How many units (runs or subjects) are processed at the same time, each by a worker of a ' ...
    'parallel pool (Parallel Computing Toolbox).\n\n' ...
    '0: one after another, no pool (the default).\n' ...
    'auto: as many workers as the computer allows (the default cluster profile, usually one ' ...
    'per physical core).\n' ...
    'A number, e.g. 4: at most that many workers.\n\n' ...
    'Each worker holds a run''s data in memory; with large data or a degree network, use fewer ' ...
    'workers than cores. Without the toolbox SeeCAT runs one after another. A pool that is ' ...
    'already open is reused as it is.']));
F(end+1) = seecat.gui.field('overwrite', 'Overwrite finished units', 'flag', 'Run', 'advanced', true, 'help', sprintf([ ...
    'A unit that already finished with the same settings is skipped. Tick to compute it again ' ...
    'anyway. A unit whose settings changed is always redone.']));
F(end+1) = seecat.gui.field('keep_work', 'Keep work files', 'flag', 'Run', 'advanced', true, 'help', ...
    'Keep the work folder of units that succeeded, e.g. to inspect intermediate images.');
end
