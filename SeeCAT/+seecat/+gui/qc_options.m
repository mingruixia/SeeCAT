function F = qc_options(withIqm)
% QC_OPTIONS  Form entries of cfg.qc (seecat.util.qc_defaults).
f = @seecat.gui.field;
F = struct('path', {}, 'label', {}, 'widget', {}, 'section', {}, 'help', {}, 'advanced', {}, 'choices', {});
if withIqm
    F(end+1) = f('qc.iqm', 'Image quality metrics (IQM)', 'flag', 'Quality control', 'help', sprintf([ ...
        'Compute MRIQC''s image quality metrics of the raw T1w and BOLD data while preprocessing ' ...
        '(the T1w segmentation, realignment and coregistration are shared, so it adds about ' ...
        'half a minute per run). BOLD: tSNR, SNR, ghost-to-signal, EFC, FBER, standardised ' ...
        'DVARS, AFNI outlier ratio and quality index, global correlation, FD, smoothness. T1w: ' ...
        'CNR, CJV, SNR (tissue and Dietrich), EFC, FBER, bias-field spread, WM-to-max, ' ...
        'volume fractions, partial-volume residuals, smoothness, and TIV.\n\n' ...
        'The values agree with MRIQC''s formulas; the masks (head, air, brain) are SeeCAT''s own, ' ...
        'so absolute values can differ from an MRIQC run. The group report shows their ' ...
        'distribution per site and warns about outliers.']));
end
F(end+1) = f('qc.max_translation', 'Max. translation (mm)', 'number', 'Quality control', 'help', sprintf([ ...
    'A run whose largest absolute translation (any axis, any frame, from realignment) is above ' ...
    'this is suggested for exclusion; 3 mm (default) is the common limit, about one voxel.']));
F(end+1) = f('qc.max_rotation', 'Max. rotation (degrees)', 'number', 'Quality control', 'help', ...
    'As Max. translation, for the largest absolute rotation; 3 degrees by default.');
F(end+1) = f('qc.max_mean_fd', 'Max. mean FD (mm)', 'number', 'Quality control', 'help', sprintf([ ...
    'A run whose mean framewise displacement (Power) is above this is suggested for exclusion: ' ...
    '0.5 mm by default; 0.2 to 0.3 mm is stricter (Parkes et al. 2018 use 0.55 lenient, 0.25 ' ...
    'stringent). Above 0.25 mm the report always warns.']));
F(end+1) = f('qc.min_coverage', 'Min. brain coverage', 'number', 'Quality control', 'help', sprintf([ ...
    'Share of the template brain mask that must lie inside the scan''s field of view after ' ...
    'normalisation (in every frame); 0.9 by default. Lower means part of the brain (often the ' ...
    'cerebellum or the top of the cortex) was not scanned; such runs are suggested for ' ...
    'exclusion. The report also shows the coverage of the top and bottom separately.']));
F(end+1) = f('qc.min_brain_dice', 'Min. brain Dice', 'number', 'Quality control', 'help', sprintf([ ...
    'Registration check: the Dice overlap of the run''s brain mask with the template brain mask ' ...
    'after normalisation (1 = identical). Runs below this, 0.85 by default, are suggested for ' ...
    'exclusion as failed normalisations; good ones are usually above 0.9.\n\n' ...
    'The reports also give, for each run: the correlation of the normalised GM, WM and CSF maps ' ...
    'with SPM''s tissue templates (reg_gm_corr ...), and the Dice of a brain mask taken from ' ...
    'the mean EPI''s own intensity with the T1w brain (reg_epi_t1_dice, EPI-T1w alignment; ' ...
    'about 0.85-0.92 when good). Outliers within a site are warnings.']));
F(end+1) = f('qc.iqm_z', 'IQM outlier z', 'number', 'Quality control', 'advanced', true, 'help', sprintf([ ...
    'An image quality metric is flagged (a warning, not an exclusion) when its robust z ' ...
    '(distance from the median in MADs) within the run''s site exceeds this in the bad ' ...
    'direction, 3 by default. Sites come from the "site" column of participants.tsv; without ' ...
    'it, or with fewer than 5 runs in a site, the whole dataset is the reference.']));
end
