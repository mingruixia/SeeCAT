function F = denoise()
% DENOISE  Form entries of the denoise, censor and smooth options
% (seecat.util.denoise_defaults), shared by prep and fmriprep.
f = @seecat.gui.field;
F = f('denoise.enable', 'Denoise', 'flag', 'Denoising', 'help', sprintf([ ...
    'Remove nuisance signal from every voxel: one regression of a polynomial trend and the ' ...
    'chosen Regressors, with data and regressors band-passed by the same filter, so the ' ...
    'filter does not bring removed signal back. The result is desc-denoised (unsmoothed), the ' ...
    'input of Seed FC and Degree.']));
F(end+1) = f('denoise.regressors', 'Regressors', 'multi', 'Denoising', ...
    'choices', {'friston24', 'wm', 'csf', 'gs', 'acompcor'}, 'help', sprintf([ ...
    'friston24: the 6 head-motion parameters, their derivatives and squares (Friston 1996).\n' ...
    'wm, csf: mean signal of the eroded white-matter and CSF masks.\n' ...
    'gs: global signal (global signal regression). Off by default: it removes widespread ' ...
    'neural signal too and creates negative correlations; tick it if your study uses it.\n' ...
    'acompcor: principal components of WM and CSF (aCompCor; see aCompCor components); use ' ...
    'it instead of wm and csf.\n\n' ...
    'Default friston24 + wm + csf. Any other column of the confounds table can be added in a ' ...
    'config file (denoise.regressors).']));
F(end+1) = f('denoise.acompcor_n', 'aCompCor components', 'number', 'Denoising', 'advanced', true, 'help', ...
    'acompcor only: components taken per tissue (WM and CSF), 5 by default (Behzadi 2007).');
F(end+1) = f('denoise.detrend_order', 'Detrend order', 'number', 'Denoising', 'advanced', true, 'help', sprintf([ ...
    'Order of the polynomial trend removed with the regressors: 0 = mean only, 1 = linear ' ...
    '(default), 2 = quadratic, up to 3.']));
F(end+1) = f('denoise.band', 'Band-pass (Hz)', 'range', 'Denoising', 'help', sprintf([ ...
    'Frequencies kept, low to high in Hz. 0.01 to 0.1 (default) is the usual resting-state ' ...
    'band. Leave the second box 0 for a high-pass only (e.g. 0.01 to 0), and both empty for no ' ...
    'filter (e.g. for ALFF-type measures computed later).']));
F(end+1) = f('censor.mode', 'High-motion frames', 'choice', 'Censoring', 'choices', {'censor', 'interp_keep', 'none'}, ...
    'help', sprintf([ ...
    'What happens to volumes with large head motion (framewise displacement above the FD ' ...
    'threshold).\n\n' ...
    'censor (default): they are filled in from the good volumes before filtering (so the ' ...
    'spike is not spread), left out of the regression, and marked in the confounds table; Seed ' ...
    'FC and Degree then leave them out. Runs keep their length.\n' ...
    'interp_keep: the same, but the filled-in volumes are used by later analyses.\n' ...
    'none: no special handling.']));
F(end+1) = f('censor.fd_threshold', 'FD threshold (mm)', 'number', 'Censoring', 'help', sprintf([ ...
    'Framewise displacement (Power et al. 2012) above which a volume counts as high-motion. ' ...
    '0.5 mm (default) is common; 0.2 to 0.3 is stricter (e.g. for children or patient ' ...
    'groups, at the cost of more lost volumes).']));
F(end+1) = f('censor.before', 'Frames before', 'number', 'Censoring', 'advanced', true, 'help', ...
    'Also flag this many volumes before each high-motion volume, 1 by default.');
F(end+1) = f('censor.after', 'Frames after', 'number', 'Censoring', 'advanced', true, 'help', ...
    'Also flag this many volumes after each high-motion volume, 2 by default (motion effects outlast the movement).');
F(end+1) = f('censor.interp', 'Interpolation', 'choice', 'Censoring', 'choices', {'spectral', 'spline'}, 'advanced', true, ...
    'help', sprintf([ ...
    'How flagged volumes are filled in before filtering.\n\n' ...
    'spectral (default): a fit of sinusoids up to the low-pass edge to the good volumes; in ' ...
    'tests it changed the good volumes and the seed maps less than spline.\n' ...
    'spline: cubic spline through the good volumes.']));
F(end+1) = f('censor.min_minutes', 'Minimum minutes', 'number', 'Censoring', 'advanced', true, 'help', sprintf([ ...
    'Runs with less good (unflagged) data than this many minutes, 5 by default, are flagged ' ...
    'in the QC report so you can exclude them.']));
F(end+1) = f('smooth.enable', 'Smooth', 'flag', 'Smoothing', 'help', sprintf([ ...
    'Also write a spatially smoothed copy of the denoised data (desc-denoisedSm<FWHM>). The ' ...
    'unsmoothed desc-denoised is always kept: Seed FC and Degree use it by default.']));
F(end+1) = f('smooth.fwhm', 'FWHM (mm)', 'number', 'Smoothing', 'help', sprintf([ ...
    'Width of the Gaussian kernel, e.g. 6 (default; about twice the voxel size) or 4. Three ' ...
    'numbers give a different FWHM per axis.']));
end
