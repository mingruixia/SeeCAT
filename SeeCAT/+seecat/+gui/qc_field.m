function f = qc_field(section)
% QC_FIELD  Form entry of qc_exclusions, shared by the analysis pages.
%   F(end+1) = seecat.gui.qc_field('Selection')
f = seecat.gui.field('qc_exclusions', 'Leave out QC exclusions', 'flag', section, 'help', sprintf([ ...
    'Ticked (default): runs (and T1w images) marked "exclude" in the derivatives folder''s ' ...
    'reports/qc_exclusions.tsv are left out, and the log lists them. That list is made by the ' ...
    'group QC report after Preprocessing or fMRIPrep denoising, from the rules there (head ' ...
    'motion, coverage, too little data); confirm or change each decision on the QC reports page.\n\n' ...
    'Untick to use every run, e.g. to compare results with and without the excluded data.']));
end
