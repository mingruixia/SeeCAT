function F = gui()
% GUI  Form description of voxel-wise degree centrality.
f = @seecat.gui.field;
F = f('input_dir', 'Derivatives folder', 'folder', 'Input', 'help', sprintf([ ...
    'The SeeCAT derivatives folder written by the Preprocessing or fMRIPrep page, e.g. ' ...
    'D:/study/bids/derivatives/seecat. It holds, per run, the preprocessed BOLD series ' ...
    '(*_desc-<input>_bold.nii.gz), the subject brain mask and the confounds table with the ' ...
    'censored frames.\n\nDegree maps are written next to them, in the same folder unless ' ...
    'Output folder is set.']));
F(end+1) = f('input', 'Input series', 'text', 'Input', 'help', sprintf([ ...
    'Which series of each run the network is built from: the desc label of the file name.\n\n' ...
    'denoised (default): denoised and band-pass filtered, NOT smoothed. Use this one: smoothing ' ...
    'before correlating inflates the connections between neighbouring voxels.\n' ...
    'Other labels, e.g. denoisedSm6, if your preprocessing wrote them.']));
F(end+1) = f('space', 'Space', 'text', 'Input', 'advanced', true, 'help', sprintf([ ...
    'Needed only when the derivatives hold the runs in more than one space, e.g. ' ...
    'MNI152NLin2009cAsym and T1w from fMRIPrep. Empty: the only space present.']));
F(end+1) = f('res', 'Resolution label', 'text', 'Input', 'advanced', true, 'help', sprintf([ ...
    'The res-<label> of the files, e.g. 2. Needed only when the derivatives hold the same runs ' ...
    'at more than one resolution (e.g. fMRIPrep res-1 and res-2). Empty: the only one present.']));
F(end+1) = f('mask', 'Mask', 'mask', 'Network', 'help', sprintf([ ...
    'The voxels that make up the network: every voxel of this mask is a node and is ' ...
    'correlated with every other.\n\n' ...
    'Grey matter (gm, default): SeeCAT''s grey-matter mask (SPM TPM GM > 0.2) resampled to the ' ...
    'data, as in SeeCAT 1.0. White matter and CSF voxels would add noise connections.\n' ...
    'Whole brain (brain): every voxel of the subject''s brain mask.\n' ...
    'Mask file: your own NIfTI image in the space of the data (MNI); voxels > 0 are kept, e.g. ' ...
    'a cortical mask or a mask shared by all subjects. Choose it with the folder button.\n\n' ...
    'The mask is always limited to the subject''s brain mask. The time and memory grow with the ' ...
    'square of the number of voxels: about 50 000 grey-matter voxels at 3 mm, 4 times more at 2 mm.']));
F(end+1) = f('group_mask', 'Same voxels in every run', 'flag', 'Network', 'help', sprintf([ ...
    'Keep only the voxels that lie inside the brain mask of every selected run (the group ' ...
    'mask), so every run''s network has the same nodes. Off (default): each run uses the mask ' ...
    'above within its own brain mask, so the number of voxels differs a little between ' ...
    'subjects, with their field of view and segmentation.\n\n' ...
    'The group mask is the intersection of the brain masks of the runs this page selects ' ...
    '(subjects, task, QC exclusions), combined with the Mask above. It is written to ' ...
    'group/masks/ in the output folder, with the list of runs in its .json. A run with poor ' ...
    'coverage makes it smaller for everyone: check the QC report, or exclude that run.\n\n' ...
    'Adding or leaving out runs changes the group mask, and the runs are then computed again.']));
F(end+1) = f('threshold', 'r threshold', 'number', 'Network', 'help', sprintf([ ...
    'A connection counts when its correlation r is at least this value (after the sign rule ' ...
    'below), e.g. 0.2 (default, as in SeeCAT 1.0), 0.25 or 0.3.\n\n' ...
    'Higher thresholds keep fewer, stronger connections. The value appears in the output name, ' ...
    'e.g. desc-degPosBinR0p2. Range 0 to below 1.']));
F(end+1) = f('sign', 'Correlations', 'multi', 'Network', 'choices', {'positive', 'absolute', 'negative'}, ...
    'help', sprintf([ ...
    'Which correlations count; each ticked option gives its own maps.\n\n' ...
    'positive (default, desc-degPos...): r >= threshold. The usual choice, since negative ' ...
    'correlations depend on the denoising (e.g. global signal regression).\n' ...
    'absolute (desc-degAbs...): |r| >= threshold, positive and negative together.\n' ...
    'negative (desc-degNeg...): -r >= threshold, the anti-correlations only.']));
F(end+1) = f('weight', 'Measures', 'multi', 'Network', 'choices', {'binary', 'weighted'}, ...
    'help', sprintf([ ...
    'What is added up over a voxel''s connections; each ticked option gives its own maps.\n\n' ...
    'binary = degree (desc-deg...Bin...): the number of connections above the threshold.\n' ...
    'weighted = strength (desc-deg...Wei...): the sum of their r values.\n\n' ...
    'Example: a voxel with 3 connections of r = 0.3, 0.5 and 0.6 has degree 3 and strength 1.4.']));
F(end+1) = f('exclude_local_mm', 'Exclude within (mm)', 'number', 'Network', 'advanced', true, ...
    'help', sprintf([ ...
    'Connections between voxels closer than this distance are not counted. Neighbouring voxels ' ...
    'correlate partly through the data''s own smoothness, so short connections can dominate ' ...
    'degree.\n\n0 (default): count all. E.g. 20: leave out connections shorter than 20 mm ' ...
    '(leaves out the immediate neighbourhood).']));
F(end+1) = f('distance_edges', 'Distance bins (mm)', 'text', 'Network', 'advanced', true, ...
    'help', sprintf([ ...
    'Splits the connections by length, with one map per bin. Give the bin edges in mm, ' ...
    'increasing, starting at 0 or more; Inf means no upper limit.\n\n' ...
    '[0 Inf] (default): one map with all connections.\n' ...
    '[0 75 Inf]: short-range (up to 75 mm) and long-range (beyond 75 mm) degree, e.g. ' ...
    'desc-degPosBinR0p2D0to75 and ...D75toInf.\n' ...
    '[0 25 75 Inf]: three bins.\n\n' ...
    'A connection of length d is in the bin lo < d <= hi.']));
F(end+1) = f('zscore', 'Also z-scored maps', 'flag', 'Output maps', 'help', sprintf([ ...
    'Also write each map z-scored within the mask (minus the mean, divided by the standard ' ...
    'deviation over the mask voxels), as stat-z next to the stat-raw maps.\n\n' ...
    'Raw degree depends on the number of voxels and the data quality of each subject; ' ...
    'z-scored maps are easier to compare between subjects and are the usual input to group ' ...
    'statistics.']));
F(end+1) = f('smooth_fwhm', 'Smooth maps', 'optnumber', 'Output maps', 'choices', 6, ...
    'help', sprintf([ ...
    'Smooth the finished maps with a Gaussian kernel of this FWHM in mm, e.g. 6 (default) or ' ...
    '4. Smoothed copies are written with Sm<fwhm> in the name (desc-degPosBinR0p2Sm6); the ' ...
    'unsmoothed maps are always kept.\n\n' ...
    'The network itself is built from the unsmoothed series, and only the maps are smoothed, ' ...
    'as group statistics usually need. Untick On to skip smoothing. Three values, e.g. ' ...
    '6 6 8, give a different FWHM per axis.']));
F = [F, seecat.gui.common(true)];
F(end+1) = seecat.gui.qc_field('Selection');
end
