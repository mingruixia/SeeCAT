function F = gui()
% GUI  Form description of the fMRIPrep denoising pipeline.
f = @seecat.gui.field;
F = f('fmriprep_dir', 'fMRIPrep folder', 'folder', 'Input', 'help', sprintf([ ...
    'The output folder of fMRIPrep, e.g. D:/study/bids/derivatives/fmriprep. SeeCAT reads, for ' ...
    'each BOLD run, *_space-<space>_desc-preproc_bold.nii.gz, its brain mask and the ' ...
    'confounds table; fMRIPrep''s own steps are not repeated.\n\n' ...
    'Results go to derivatives/seecat next to it unless Output folder is set, with the same ' ...
    'names as the Preprocessing page, so Seed FC, Degree and Statistics work the same way.']));
F(end+1) = f('space', 'Space', 'text', 'Input', 'help', sprintf([ ...
    'Which fMRIPrep output space to denoise, the space-<label> in the file names. Default ' ...
    'MNI152NLin2009cAsym. Group analyses need a template space, not T1w or fsnative.']));
F(end+1) = f('res', 'Resolution label', 'text', 'Input', 'advanced', true, 'help', sprintf([ ...
    'The res-<label> of the files, e.g. 2, needed only when fMRIPrep wrote the space at more ' ...
    'than one resolution. Empty: the only one present.']));
F(end+1) = f('dummy_scans', 'Dummy scans', 'text', 'Input', 'advanced', true, 'help', sprintf([ ...
    'Volumes removed from the start of each run.\n\n' ...
    'auto (default): those fMRIPrep marked as non-steady-state (non_steady_state_outlier ' ...
    'columns).\nA number, e.g. 5: that many from every run.']));
F = [F, seecat.gui.denoise(), seecat.gui.qc_options(false), seecat.gui.common(true)];
end
