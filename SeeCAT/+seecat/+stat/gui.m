function F = gui()
% GUI  Form description of group statistics.
f = @seecat.gui.field;
F = f('name', 'Analysis name', 'text', 'Input', 'help', sprintf([ ...
    'A name for this analysis, letters and digits only, e.g. PCCzSCHZvsCTL. Results go to ' ...
    '<output folder>/group/<name>/ and every file starts with it, so different analyses of the ' ...
    'same data stay apart. Running again with the same name and settings skips the analysis ' ...
    '(tick Overwrite to redo it).']));
F(end+1) = f('input_dir', 'Derivatives folder', 'folder', 'Input', 'help', sprintf([ ...
    'The SeeCAT derivatives folder that holds the per-subject maps, e.g. ' ...
    'D:/study/bids/derivatives/seecat (the output of Seed FC or Degree).\n\n' ...
    'Once it is set, the Maps fields below list the values found there.']));
F(end+1) = f('maps', 'Maps', 'maps', 'Input', 'help', sprintf([ ...
    'Which per-subject map enters the analysis, by the parts of its file name. Every subject ' ...
    'must have exactly one matching map (two for paired designs, one per level).\n\n' ...
    'Map (desc): the seed or measure, e.g. PCC (seed FC) or degPosBinR0p2Sm6 (degree).\n' ...
    'Statistic (stat): z (Fisher z of r, or z-scored degree; the usual choice) or raw.\n' ...
    'Suffix: connectivity for SeeCAT''s maps.\n' ...
    'Space and Task: needed only when several are present.\n' ...
    'Other: further entities as key=value, comma separated, e.g. ses=1, run=1.\n\n' ...
    'Open a list to pick from the values in the derivatives folder, or type a value. Empty ' ...
    'fields match anything. The line below the fields counts the matching maps.\n\n' ...
    'Example: sub-01_task-rest_space-MNI152NLin2009cAsym_desc-PCC_stat-z_connectivity.nii.gz ' ...
    'is chosen by Map PCC, Statistic z, Suffix connectivity.']));
F(end+1) = f('participants', 'participants.tsv', 'file', 'Input', 'advanced', true, 'help', sprintf([ ...
    'The table of subject information (group, age, sex, ...) with a participant_id column ' ...
    '(sub-01, ...). Empty: participants.tsv of the BIDS dataset the derivatives come from.\n\n' ...
    'Factor, Regressors and Covariates name its columns. Subjects with an empty or n/a value ' ...
    'in a used column are left out and listed in the log.']));
F(end+1) = f('design', 'Design', 'choice', 'Model', 'choices', ...
    {'one_sample', 'two_sample', 'paired', 'anova1', 'anova1_rm', 'regression', 'custom'}, ...
    'help', sprintf([ ...
    'one_sample: is the mean map different from 0? (e.g. the PCC network of all subjects). ' ...
    'Contrasts pos and neg.\n' ...
    'two_sample: do two groups differ? Factor = the participants column of the group; ' ...
    'contrasts AgtB and BgtA.\n' ...
    'paired: two maps per subject (e.g. ses-1 and ses-2, before and after); Factor = the ' ...
    'entity that differs (ses, desc, ...).\n' ...
    'anova1: three or more groups; F contrast of equal means.\n' ...
    'anova1_rm: three or more maps per subject (repeated measures); F contrast.\n' ...
    'regression: does the map vary with a score (age, symptoms)? Regressors = the columns; ' ...
    'contrasts <name>pos and <name>neg.\n' ...
    'custom: your own design matrix (Design TSV) and Contrasts.']));
F(end+1) = f('factor', 'Factor', 'text', 'Model', 'help', sprintf([ ...
    'two_sample and anova1: the participants.tsv column that holds the group, e.g. diagnosis.\n' ...
    'paired and anova1_rm: the file-name entity whose value differs between a subject''s maps, ' ...
    'e.g. ses (sessions) or desc (two seeds or measures).\n' ...
    'Not used by the other designs.']));
F(end+1) = f('levels', 'Levels', 'labels', 'Model', 'help', sprintf([ ...
    'The levels of Factor in the order the contrasts use, comma separated, e.g. CONTROL, SCHZ: ' ...
    'AgtB is then CONTROL > SCHZ. Levels not listed are left out, so this also picks two ' ...
    'groups out of several. Empty: all levels, in the order found.']));
F(end+1) = f('regressors', 'Regressors', 'labels', 'Model', 'help', sprintf([ ...
    'regression only: participants.tsv columns of the scores tested, comma separated, e.g. ' ...
    'age or PANSS_total, MoCA. They are mean-centred and fitted in one model, so each is ' ...
    'tested adjusted for the others.']));
F(end+1) = f('covariates', 'Covariates', 'labels', 'Model', 'help', sprintf([ ...
    'participants.tsv columns to adjust for (not tested), comma separated, e.g. age, sex, ' ...
    'mean_fd. Numbers are mean-centred; text columns (e.g. sex, site) become centred dummy ' ...
    'columns. The log warns when a column is strongly collinear with others (VIF > 5). ' ...
    'Paired and repeated-measures designs cannot take between-subject covariates.']));
F(end+1) = f('design_tsv', 'Design TSV', 'file', 'Model', 'advanced', true, 'help', sprintf([ ...
    'custom design only: a tab-separated table with a path column (the map of each row, ' ...
    'absolute or relative to the table) and one numeric column per design column, e.g.\n' ...
    'path  A  B  age\nsub-01_map.nii  1  0  23\n...\n' ...
    'Contrasts then have one weight per design column, in this order.']));
F(end+1) = f('contrasts', 'Contrasts', 'contrasts', 'Model', 'advanced', true, 'help', sprintf([ ...
    'One row per contrast: a name (letters and digits), type t or F, and the weights, one per ' ...
    'design column (see <name>_design.tsv of a first run for the columns and their order). ' ...
    'F weights have one row per line, separated by ";", e.g. [1 -1 0; 0 1 -1].\n\n' ...
    'Empty: the design''s defaults (both directions of each T test, or the F test of ' ...
    'equal means).']));
F(end+1) = f('variance', 'Variance', 'choice', 'Model', 'choices', {'auto', 'equal', 'unequal'}, ...
    'advanced', true, 'help', sprintf([ ...
    'Whether the groups or levels may have different variances (and, for repeated measures, ' ...
    'correlated levels), as SPM''s non-sphericity.\n\n' ...
    'auto (default): equal, except unequal for anova1_rm.\n' ...
    'equal: one variance for all (ordinary least squares).\n' ...
    'unequal: estimated with ReML over the strongly responding voxels, as SPM does.']));
F(end+1) = f('mask', 'Mask', 'mask', 'Inference', 'help', sprintf([ ...
    'The voxels tested.\n\n' ...
    'Grey matter (gm, default): SeeCAT''s grey-matter mask (SPM TPM GM > 0.2).\n' ...
    'Whole brain (brain): no extra mask.\n' ...
    'Mask file: your own NIfTI image in MNI space (voxels > 0), e.g. a region of interest for ' ...
    'a small-volume analysis; choose it with the folder button.\n\n' ...
    'In every case only voxels that are non-zero in every subject''s map are kept. A smaller ' ...
    'mask means a milder correction.']));
F(end+1) = f('inference', 'Correction', 'multi', 'Inference', 'choices', ...
    {'cluster_fwe', 'voxel_fwe', 'voxel_fdr', 'tfce_fwe'}, 'help', sprintf([ ...
    'How the maps are corrected for multiple comparisons; each ticked method gives its own ' ...
    'thresholded map and cluster table (desc-clusterFWE, -voxelFWE, -voxelFDR, -tfceFWE).\n\n' ...
    'cluster_fwe (default): clusters above the cluster-forming p, kept when their size has ' ...
    'FWE p < Alpha (random field theory, as SPM).\n' ...
    'voxel_fwe: voxels with FWE p < Alpha (random field theory, as SPM); strict.\n' ...
    'voxel_fdr: voxels with false discovery rate < Alpha (Benjamini-Hochberg).\n' ...
    'tfce_fwe: threshold-free cluster enhancement with FWE p from permutations (as FSL ' ...
    'randomise); no cluster-forming threshold to choose, robust, but slow: see TFCE ' ...
    'permutations and Parallel workers.\n\n' ...
    'Unthresholded T/F, Z, p and effect maps are always written.']));
F(end+1) = f('cdt_p', 'Cluster-forming p', 'number', 'Inference', 'help', sprintf([ ...
    'cluster_fwe only: voxels below this uncorrected p form the clusters. 0.001 (default) is ' ...
    'the recommended value; above 0.001 random field theory clusters are too liberal ' ...
    '(Eklund et al. 2016), and the log warns.']));
F(end+1) = f('alpha', 'Alpha', 'number', 'Inference', 'help', sprintf([ ...
    'The corrected significance level of every method, e.g. 0.05 (default). With Two-tailed, ' ...
    'each T contrast is tested at Alpha/2.']));
F(end+1) = f('two_tailed', 'Two-tailed (alpha/2 per T contrast)', 'flag', 'Inference', 'help', sprintf([ ...
    'The default T contrasts come in pairs (AgtB and BgtA, pos and neg), one per direction. ' ...
    'Ticked (default): each is tested at Alpha/2, so the pair together is a two-tailed test ' ...
    'at Alpha. Untick only for a direction chosen before looking at the data.']));
F(end+1) = f('tfce.n_perm', 'TFCE permutations', 'number', 'Inference', 'help', sprintf([ ...
    'tfce_fwe only: how many permutations (sign flips for one_sample, swaps within subjects ' ...
    'for paired designs) build the null distribution. 5000 (default) as FSL randomise; the ' ...
    'smallest possible p is 1/permutations. When fewer distinct permutations exist (e.g. 2^n ' ...
    'sign flips of n maps), all are used.\n\n' ...
    'Time grows with the permutations, the contrasts and the mask: several minutes to an hour. ' ...
    'Parallel workers (Run) share the permutations. The random seed is fixed, so results ' ...
    'repeat exactly.']));
F(end+1) = f('tfce.E', 'TFCE extent exponent E', 'number', 'Inference', 'advanced', true, 'help', ...
    'TFCE weight of cluster extent, 0.5 (default, Smith & Nichols 2009; as FSL for 3D data).');
F(end+1) = f('tfce.H', 'TFCE height exponent H', 'number', 'Inference', 'advanced', true, 'help', ...
    'TFCE weight of height, 2 (default, Smith & Nichols 2009; as FSL).');
F = [F, seecat.gui.common(false)];
F(end+1) = f('subjects', 'Subjects', 'labels', 'Input', 'advanced', true, 'help', sprintf([ ...
    'Only these subjects, labels without "sub-", comma separated. Empty: every subject with a ' ...
    'matching map.']));
k = strcmp({F.path}, 'n_workers');
F(k).help = sprintf([ ...
    'Used only by tfce_fwe: the permutations are shared among this many workers of a parallel ' ...
    'pool (Parallel Computing Toolbox). The other corrections run in seconds and ignore it.\n\n' ...
    '0: no pool (default).\nauto: as many workers as fit in memory (each holds the maps of all ' ...
    'subjects, plus about 1 GB), at most one per core; the log shows the estimate.\n' ...
    'A number, e.g. 8: at most that many.']);
end
