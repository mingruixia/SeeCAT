function F = gui()
% GUI  Form description of seed-based FC.
f = @seecat.gui.field;
F = f('input_dir', 'Derivatives folder', 'folder', 'Input', 'help', 'Output of prep or fmriprep');
F(end+1) = f('input', 'Input series', 'text', 'Input', 'help', 'desc label: denoised, or e.g. denoisedSm6');
F(end+1) = f('space', 'Space', 'text', 'Input', 'advanced', true);
F(end+1) = f('seeds', 'Seeds', 'seeds', 'Seeds', 'help', sprintf(['One row per seed; spheres and masks can be ' ...
    'mixed. Sphere: centre in MNI mm as "x y z" and a radius in mm, e.g. PCC, 0 -53 26, 6. Mask: a NIfTI ' ...
    'image in MNI space (any voxel size); voxels above 0 are the seed. Add mask files adds one row per ' ...
    'file, named after it; Choose file sets the file of the selected row. Names are letters and digits ' ...
    'and name the output maps (desc-<name>). The Check column says what a row still needs.']));
F = [F, seecat.gui.common(true)];
end
