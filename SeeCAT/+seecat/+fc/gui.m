function F = gui()
% GUI  Form description of seed-based FC.
f = @seecat.gui.field;
F = f('input_dir', 'Derivatives folder', 'folder', 'Input', 'help', sprintf([ ...
    'The SeeCAT derivatives folder written by the Preprocessing or fMRIPrep page, e.g. ' ...
    'D:/study/bids/derivatives/seecat. It holds, per run, the denoised BOLD series, the brain ' ...
    'mask and the confounds table with the censored frames.\n\n' ...
    'The maps are written next to the runs (desc-<seed>_stat-r and stat-z), in the same ' ...
    'folder unless Output folder is set.']));
F(end+1) = f('input', 'Input series', 'text', 'Input', 'help', sprintf([ ...
    'Which series of each run is used: the desc label of the file name.\n\n' ...
    'denoised (default): denoised, band-passed, not smoothed. The seed signal then comes only ' ...
    'from the seed''s own voxels.\n' ...
    'denoisedSm6 (or another Sm label your preprocessing wrote): the smoothed series, as in ' ...
    'many published FC studies; the maps are then smooth without a further step.']));
F(end+1) = f('space', 'Space', 'text', 'Input', 'advanced', true, 'help', sprintf([ ...
    'Needed only when the derivatives hold the runs in more than one space. Empty: the only ' ...
    'space present.']));
F(end+1) = f('res', 'Resolution label', 'text', 'Input', 'advanced', true, 'help', sprintf([ ...
    'The res-<label> of the files, e.g. 2. Needed only when the derivatives hold the same runs ' ...
    'at more than one resolution (e.g. fMRIPrep res-1 and res-2). Empty: the only one present.']));
F(end+1) = f('seeds', 'Seeds', 'seeds', 'Seeds', 'help', sprintf([ ...
    'One row per seed; spheres and masks can be mixed. For each run and seed, the mean signal ' ...
    'of the seed''s voxels (inside the brain mask, censored frames left out) is correlated ' ...
    'with every voxel: a map of r and of Fisher z (desc-<name>_stat-z, the one to use in ' ...
    'Statistics).\n\n' ...
    'Sphere: centre in MNI mm as "x y z" and a radius in mm, e.g. PCC: 0 -53 26, radius 6; ' ...
    'mPFC: 0 52 -6; left motor cortex: -38 -22 56.\n' ...
    'Mask: a NIfTI image in MNI space (any voxel size; voxels above 0 are the seed), e.g. an ' ...
    'atlas region saved as a binary mask. It is resampled to the data.\n\n' ...
    'Add sphere adds a row; Add mask files adds one row per chosen file, named after it; ' ...
    'Choose file sets the file of the selected row; Remove deletes the selected rows. Names ' ...
    'are letters and digits and name the output maps. The Check column says what a row still ' ...
    'needs.']));
F(end+1) = f('mask', 'Mask', 'mask', 'Maps', 'help', sprintf([ ...
    'The voxels the maps cover.\n\n' ...
    'Whole brain (brain, default): every voxel of the subject''s brain mask.\n' ...
    'Grey matter (gm): SeeCAT''s grey-matter mask (SPM TPM GM > 0.2) resampled to the data.\n' ...
    'Mask file: your own NIfTI image in the space of the data (MNI); voxels > 0 are kept, e.g. ' ...
    'a mask shared by all subjects.\n\n' ...
    'The mask is limited to the subject''s brain mask, unless "Use the mask as given" is on. ' ...
    'It does not change the seeds: they take their voxels from the brain mask either way.']));
F(end+1) = f('group_mask', 'Same voxels in every run', 'flag', 'Maps', 'help', sprintf([ ...
    'Use only the voxels that lie inside the brain mask of every selected run (the group ' ...
    'mask): each seed then has the same voxels in every run, and every map covers the same ' ...
    'voxels. Off (default): each run uses its own brain mask, which differs a little between ' ...
    'subjects with their field of view and segmentation; a seed at the edge of the scan can ' ...
    'then have fewer voxels in some runs.\n\n' ...
    'The group mask is the intersection of the brain masks of the runs this page selects ' ...
    '(subjects, task, QC exclusions). It is written to group/masks/ in the output folder, with ' ...
    'the list of runs in its .json. A run with poor coverage makes it smaller for everyone: ' ...
    'check the QC report, or exclude that run. Adding or leaving out runs changes the group ' ...
    'mask, and the runs are then computed again.']));
F(end+1) = f('mask_only', 'Use the mask as given', 'flag', 'Maps', 'help', sprintf([ ...
    'Use every voxel of the Mask above, without limiting it to the subject''s brain mask: every ' ...
    'run''s maps then cover exactly the voxels of the mask, and each seed uses all its own ' ...
    'voxels that carry signal. Off (default): the brain mask of each run limits both.\n\n' ...
    'Needs grey matter (gm) or a mask file as the Mask, and cannot go with "Same voxels in ' ...
    'every run". Outside a run''s brain mask or field of view the denoised series is 0, so ' ...
    'r and z are 0 there. The log of each run gives how many voxels lie outside its brain ' ...
    'mask.']));
F = [F, seecat.gui.common(true)];
F(end+1) = seecat.gui.qc_field('Selection');
end
