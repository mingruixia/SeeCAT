function F = gui()
% GUI  Form description of the preprocessing pipeline (seecat.gui.form).
f = @seecat.gui.field;
F = f('bids_dir', 'BIDS folder', 'folder', 'Input', 'help', sprintf([ ...
    'The raw BIDS dataset, e.g. D:/study/bids, with sub-<label>/anat/*_T1w.nii.gz and ' ...
    'sub-<label>/func/*_bold.nii.gz plus their JSON sidecars (DICOM to BIDS writes this).\n\n' ...
    'Results go to <BIDS folder>/derivatives/seecat unless Output folder is set. Use Data check ' ...
    'first to see the runs, TR and head motion.']));
F(end+1) = f('dummy_scans', 'Dummy scans', 'text', 'Input', 'advanced', true, 'help', sprintf([ ...
    'Volumes removed from the start of each run, before the signal is steady.\n\n' ...
    'auto (default): detected from the data (leading volumes whose mean brain intensity is an ' ...
    'outlier). Scanners that already discard them give none.\n' ...
    'A number, e.g. 5: remove that many from every run.']));
F(end+1) = f('slice_timing.enable', 'Slice timing', 'flag', 'Preprocessing', 'help', sprintf([ ...
    'Correct for the different acquisition times of the slices within a volume (SPM slice ' ...
    'timing). On by default; it needs the slice times (SliceTiming in the sidecar, written by ' ...
    'dcm2niix). Turn it off when the slice times are unknown.']));
F(end+1) = f('slice_timing.slice_times', 'Slice times (s)', 'text', 'Preprocessing', 'advanced', true, ...
    'help', sprintf([ ...
    'auto (default): SliceTiming from each run''s JSON sidecar.\n' ...
    'Otherwise the acquisition time of every slice in seconds, in slice order, e.g. for 4 ' ...
    'interleaved slices and TR 2: 0 1 0.5 1.5.']));
F(end+1) = f('slice_timing.ref_time', 'Reference time', 'text', 'Preprocessing', 'advanced', true, ...
    'help', sprintf([ ...
    'The time within the TR that all slices are shifted to.\n\n' ...
    'middle (default): half the TR.\nA number in seconds, e.g. 0 for the first slice.']));
F(end+1) = f('realign.enable', 'Realign', 'flag', 'Preprocessing', 'advanced', true, 'help', sprintf([ ...
    'Correct head motion by aligning every volume (SPM realign). The six motion parameters and ' ...
    'framewise displacement go into the confounds table. Keep it on.']));
F(end+1) = f('realign.register_to_mean', 'Register to mean', 'flag', 'Preprocessing', 'advanced', true, ...
    'help', sprintf([ ...
    'Two passes: first to the first volume, then to the mean of the aligned volumes (SPM''s ' ...
    '"register to mean"). More accurate; on by default.']));
F(end+1) = f('normalise.enable', 'Normalise', 'flag', 'Preprocessing', 'advanced', true, 'help', sprintf([ ...
    'Bring the data into MNI space (SPM''s IXI549Space template) so subjects can be compared ' ...
    'voxel by voxel. Needed by the group analyses.']));
F(end+1) = f('normalise.method', 'Normalisation', 'choice', 'Preprocessing', 'choices', {'auto', 'segment', 'epi'}, ...
    'help', sprintf([ ...
    'auto (default): segment when the subject has a T1w image, otherwise epi.\n' ...
    'segment: the T1w image is segmented (SPM unified segmentation) and its deformation applied ' ...
    'to the functional data, after registering the mean EPI to the T1w. The most accurate.\n' ...
    'epi: the mean EPI is normalised directly to the tissue templates; for data without a T1w.']));
F(end+1) = f('normalise.voxel_size', 'Voxel size (mm)', 'number', 'Preprocessing', 'help', sprintf([ ...
    'Voxel size of the normalised data, e.g. 3 (default) or 2. Smaller voxels need more disk ' ...
    'and memory (a 2 mm run is 3.4 times as large) and make Degree much slower. Three numbers, ' ...
    'e.g. 3 3 4, give different sizes per axis.']));
F(end+1) = f('normalise.bounding_box', 'Bounding box', 'text', 'Preprocessing', 'advanced', true, 'help', sprintf([ ...
    'The extent of the normalised images in MNI mm, [xmin ymin zmin; xmax ymax zmax]. Default ' ...
    '[-90 -126 -72; 90 90 108], SPM''s box, which holds the whole brain and cerebellum.']));
F(end+1) = f('masks.wm_threshold', 'WM probability', 'number', 'Nuisance masks', 'advanced', true, 'help', sprintf([ ...
    'White-matter mask for the wm regressor (and aCompCor): voxels whose WM probability from ' ...
    'segmentation is above this, 0.99 by default, then eroded. A strict mask keeps grey-matter ' ...
    'signal out of the nuisance signal.']));
F(end+1) = f('masks.csf_threshold', 'CSF probability', 'number', 'Nuisance masks', 'advanced', true, 'help', sprintf([ ...
    'CSF mask for the csf regressor: CSF probability above this, 0.95 by default (0.99 eroded ' ...
    'can leave no voxels in small ventricles), then eroded.']));
F(end+1) = f('masks.erode_mm', 'Erosion (mm)', 'number', 'Nuisance masks', 'advanced', true, 'help', sprintf([ ...
    'The WM and CSF masks are shrunk by a ball of this radius (2 mm by default) in the ' ...
    'subject''s own space, away from grey matter. 0: no erosion.']));
F = [F, seecat.gui.denoise(), seecat.gui.common(true)];
end
