function F = gui()
% GUI  Form description of multi-site harmonisation.
f = @seecat.gui.field;
F = f('input_dir', 'Derivatives folder', 'folder', 'Input', 'help', sprintf([ ...
    'The SeeCAT derivatives folder with the per-subject maps to harmonise (output of Seed FC, ' ...
    'Degree or Gradients), e.g. D:/study/bids/derivatives/seecat. The harmonised maps are ' ...
    'written next to the originals unless Output folder is set.']));
F(end+1) = f('maps', 'Maps', 'maps', 'Input', 'help', sprintf([ ...
    'Which maps to harmonise, by the parts of their file names, as in Statistics: e.g. Map ' ...
    'PCC and Statistic z for seed FC, or Map grad1Vox4 for the first gradient. Open a list to ' ...
    'pick from the values found; the line below counts the matching maps.\n\n' ...
    'Harmonise each kind of map separately (one run of this page per measure). All maps of all ' ...
    'sites are needed together.']));
F(end+1) = f('participants', 'participants.tsv', 'file', 'Input', 'advanced', true, 'help', sprintf([ ...
    'The table with participant_id, the site column and the covariates. Empty: ' ...
    'participants.tsv of the BIDS dataset the derivatives come from.']));
F(end+1) = f('site', 'Site column', 'text', 'Model', 'help', sprintf([ ...
    'The participants.tsv column that names the site or scanner of each subject, e.g. site, ' ...
    'scanner or center. Every site needs at least 2 subjects; ComBat works best with 10 or ' ...
    'more per site. A study scanned on two scanners at one centre has two sites.']));
F(end+1) = f('method', 'Method', 'choice', 'Model', 'choices', ...
    {'combat', 'combat_nonparam', 'combat_noeb', 'combat_mean', 'combat_gam', 'covbat', 'lm'}, ...
    'help', sprintf([ ...
    'combat (default): ComBat with parametric empirical Bayes (Johnson et al. 2007; Fortin ' ...
    'et al. 2017, 2018). Site differences in the mean and variance of every voxel are removed; ' ...
    'the estimates borrow strength across voxels, which helps small sites. Same results as ' ...
    'neuroCombat.\n' ...
    'combat_nonparam: empirical Bayes without assuming a distribution for the site effects; ' ...
    'slower (prior from up to 5000 other voxels).\n' ...
    'combat_noeb: location and scale per voxel without shrinkage; for large sites.\n' ...
    'combat_mean: site means only, variances left as they are.\n' ...
    'combat_gam: ComBat-GAM (Pomponio et al. 2020): Nonlinear covariates such as age are kept ' ...
    'as smooth curves, for wide age ranges.\n' ...
    'covbat: CovBat (Chen et al. 2022): ComBat, then also the site differences in how voxels ' ...
    'co-vary are removed.\n' ...
    'lm: linear regression; site means removed with the covariates in the model, no ' ...
    'empirical Bayes or scaling.\n\n' ...
    'Small sites (fewer than about 20 subjects each): the variance adjustment of combat, ' ...
    'combat_nonparam, combat_noeb, combat_gam and covbat can make later tests of the kept ' ...
    'covariates too liberal (Nygaard et al. 2016). In the manual''s example (3 sites of 10, ' ...
    'simulated age) a GM-age regression found 3 false clusters after combat and none after ' ...
    'combat_mean or lm. Prefer combat_mean or lm for small samples; the log warns.']));
F(end+1) = f('covariates', 'Covariates kept', 'labels', 'Model', 'help', sprintf([ ...
    'participants.tsv columns whose effects must survive harmonisation, comma separated, e.g. ' ...
    'diagnosis, age, sex. Text columns become categories. Include every variable you will ' ...
    'test later: an effect that is not listed and differs between sites is partly removed ' ...
    'with the site effect.']));
F(end+1) = f('nonlinear', 'Nonlinear covariates', 'labels', 'Model', 'help', sprintf([ ...
    'Numeric columns kept as smooth (natural spline) effects instead of straight lines, e.g. ' ...
    'age over a lifespan sample. Needed by combat_gam; allowed with every method. Do not list ' ...
    'a column in both boxes.']));
F(end+1) = f('spline_df', 'Spline df', 'number', 'Model', 'advanced', true, 'help', ...
    'Degrees of freedom of each nonlinear covariate''s spline, 3 by default; more allow wigglier curves.');
F(end+1) = f('ref_site', 'Reference site', 'text', 'Model', 'advanced', true, 'help', sprintf([ ...
    'A site whose maps are left unchanged; the other sites are mapped onto it (e.g. the ' ...
    'largest site, or the one a normative model was built on). Empty (default): all sites ' ...
    'are mapped to their common average.']));
F(end+1) = f('covbat_var', 'CovBat variance', 'number', 'Model', 'advanced', true, 'help', ...
    'covbat only: share of the residual variance whose principal components are harmonised, 0.95 by default.');
F(end+1) = f('mask', 'Mask', 'mask', 'Model', 'help', sprintf([ ...
    'The voxels harmonised: grey matter (gm, default), whole brain, or a mask file; always only ' ...
    'voxels that are non-zero in every map. Voxels outside are 0 in the outputs, so ' ...
    'Statistics leaves them out.']));
F(end+1) = f('label', 'Output label', 'text', 'Output', 'help', sprintf([ ...
    'Added to the desc label of each map, e.g. desc-PCC -> desc-PCCComBat (default ComBat). ' ...
    'Use another label to keep the results of different methods apart (e.g. CovBat). In ' ...
    'Statistics, choose Map PCCComBat.']));
F = [F, seecat.gui.common(false)];
F(end+1) = seecat.gui.qc_field('Input');
F(end+1) = f('subjects', 'Subjects', 'labels', 'Input', 'advanced', true, 'help', ...
    'Only these subjects, labels without "sub-", comma separated. Empty: all with a matching map.');
F = F(~strcmp({F.path}, 'n_workers'));        % one fast step over all maps: nothing to share
end
