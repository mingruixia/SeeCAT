function missing = sc_check_dpabi(showDialog)
% SC_CHECK_DPABI  List DPABI functions the legacy viewer/correction tools call
% but SeeCAT does not ship. Until the viewer is replaced, these features need
% DPABI on the MATLAB path.
%
%   missing = sc_check_dpabi        % warn in a dialog if anything is missing
%   missing = sc_check_dpabi(false) % only return the list

if nargin < 1
    showDialog = true;
end
needed = { ...
    'w_Montage',          'Montage view'; ...
    'w_ClusterSize',      'Cluster size threshold'; ...
    'w_OverlayConfig',    'Overlay settings'; ...
    'w_TimeCourse',       'Time course plot'; ...
    'w_AtlasSelect',      'Atlas selection'; ...
    'w_StructuralSelect', 'Structural image selection'; ...
    'w_colormapeditor',   'Colormap editor'; ...
    'y_ClusterReport',    'Cluster report'; ...
    'y_CallBrainNetViewer','Surface view via BrainNet Viewer'; ...
    'y_GRF_Threshold',    'GRF correction'; ...
    'y_TFRtoZ',           'GRF correction'; ...
    'y_Smoothest',        'GRF correction'};
isMissing = cellfun(@(f) ~exist(f, 'file'), needed(:, 1));
missing = needed(isMissing, :);
if showDialog && ~isempty(missing)
    features = unique(missing(:, 2), 'stable');
    warndlg([{'These viewer features need DPABI on the MATLAB path and will not work:'}; ...
        strcat({'  - '}, features); ...
        {''; 'Add DPABI (http://rfmri.org/DPABI) to the path to enable them.'}], ...
        'SeeCAT: DPABI not found');
end
end
